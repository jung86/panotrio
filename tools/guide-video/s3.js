// 3. 모터 컨디션 점수
const { open, quickStick, quickDps } = require('./lib');
module.exports = async () => {
  const S = await open('s3', { seed: { 'panotrio-motors': JSON.stringify(['하이퍼대시3 #1']), 'panotrio-motor': '하이퍼대시3 #1' } });
  const p = S.p;
  await quickStick(S);
  await p.click('#tileMeasure'); await S.wait(800);
  await quickDps(S);
  await p.evaluate(() => { const i = document.getElementById('psuV'); i.value = '2'; i.dispatchEvent(new Event('change')); SIM.ifac = 1.12; SIM.kf = 0.965; SIM.inoise = 0.2; SIM.hnoise = 0.035; });
  await p.evaluate(() => document.getElementById('condCard').scrollIntoView({ block: 'start' })); await S.wait(800);
  S.mark('start');
  await S.cap('🩺 모터 컨디션 점수', '같은 전압으로 일정 시간 돌려서 100점 만점으로 매깁니다'); await S.wait(3500);
  await S.cap('전원공급기와 스틱을 연결하고', '기록 카드에서 모터를 골라 두면 모터별로 비교됩니다'); await S.wait(3200);
  await S.cap('① 측정 시간을 고릅니다 (기본 30초)'); await S.wait(500);
  const sel = p.locator('#ckDur'); const bb = await sel.boundingBox();
  await p.evaluate(([x, y]) => window.__ring(x, y), [bb.x + bb.width / 2, bb.y + bb.height / 2]); await S.wait(500);
  await sel.selectOption('15'); await S.wait(1200);
  await S.cap('② 청소하기 전에 [🧽 청소 전]을 누릅니다'); await S.wait(600);
  await S.tap('#ckTag button[data-t="1"]', 1200);
  await S.cap('출력 켜기 → 측정 → 점수 → 출력 끄기까지 알아서 합니다', '▶▶ 빠르게 보기'); await S.wait(2500);
  S.mark('ff1@3');
  await p.waitForFunction(() => !ck && document.getElementById('ckRes').textContent.trim().length > 0, null, { timeout: 60000 });
  S.mark('nf1');
  await S.wait(600);
  await S.cap('점수와 등급이 나옵니다', '85점 이상 좋음 · 65점 이상 보통 · 그 아래 점검 필요'); await S.wait(500);
  await S.scrollTo('#ckRes', 'start'); await S.wait(4000);
  await S.cap('감점 이유도 함께 보여 줍니다', '전류가 출렁이면 브러시·정류자를 의심'); await S.wait(3500);
  await p.evaluate(() => { SIM.ifac = 1.0; SIM.kf = 1.0; SIM.inoise = 0.012; SIM.hnoise = 0.0025; });
  await S.cap('③ 모터를 청소한 뒤 [✨ 청소 후]'); await S.wait(400);
  await S.tap('#ckTag button[data-t="2"]', 1200);
  await S.cap('같은 전압으로 다시 잽니다', '▶▶ 빠르게 보기'); await S.wait(2000);
  S.mark('ff2@3');
  await p.waitForFunction(() => !ck && /청소 후/.test(document.getElementById('ckRes').textContent), null, { timeout: 60000 });
  S.mark('nf2');
  await S.wait(600);
  await S.cap('청소 전·후 비교', '전류가 줄고 회전이 빨라졌는지 한눈에'); await S.wait(500);
  await S.scrollTo('#ckCmp', 'start'); await S.wait(5000);
  await S.cap('결과는 [기록 · 비교]에 모터별로 쌓입니다'); await S.wait(3000);
  await S.cap(''); await S.wait(400); S.mark('end');
  return S;
};
